function benchmark = get_revision_benchmark_config(case_id)
%GET_REVISION_BENCHMARK_CONFIG Canonical 20D Figure-6 Algorithm-2 case.
arguments
    case_id (1,1) double {mustBeInteger,mustBeMember(case_id,[2,3,4])} = 4
end
figure6 = config_ackley();
panel_index = case_id+3;
benchmark = figure6(panel_index);
assert(benchmark.problem.dimension==20, ...
    'get_revision_benchmark_config:DimensionMismatch', ...
    'The selected revision benchmark must be 20-dimensional.');
assert(isequal(benchmark.methods, ...
    {'proposed','quadratic-penalty-cbo','cb2o'}) ...
    && strcmp(benchmark.proposed_solver,'algorithm2'), ...
    'get_revision_benchmark_config:AlgorithmMismatch', ...
    'The selected revision benchmark must use Algorithm 2.');
end
