function compact = compact_revision_result(result)
%COMPACT_REVISION_RESULT Retain metrics and metadata without particle arrays.
% Check finiteness of the full final ensemble before calling this function.
required = {'v_out','objective_value','objective_gap','G_value', ...
    'feasibility_error','distance_to_vstar','success','iterations', ...
    'exit_reason','output_source','alpha','epsilon','alpha_over_epsilon', ...
    'initial_seed','stochastic_seed','solver_seed','repetition', ...
    'concentration_event_count','restart_count', ...
    'best_incumbent_update_count','runtime','runtime_seconds','all_finite'};
missing = required(~isfield(result,required));
assert(isempty(missing),'compact_revision_result:MissingField', ...
    'The augmented full result is missing required field(s): %s', ...
    strjoin(missing,', '));

analysis_fields = [required,{'objective_error','relative_objective_error', ...
    'infinity_distance_to_vstar','l1_feasibility','seed','method', ...
    'problem_name','benchmark_id','case_id','alpha_index','epsilon_index', ...
    'arm','arm_label','sigma_indep'}];
compact = struct();
for index=1:numel(analysis_fields)
    name = analysis_fields{index};
    if isfield(result,name)
        compact.(name) = result.(name);
    end
end

% The full solver configuration is stored once per experiment.
solver_scalar_fields = {'particles','lambda','sigma','gamma','max_steps', ...
    'concentration_tol','improvement_tol','sigma_indep','store_trajectory', ...
    'success_distance_tol','success_infinity_distance_tol', ...
    'success_feasibility_tol','success_relative_objective_tol', ...
    'success_l1_feasibility_tol'};
if isfield(result,'config')
    for index=1:numel(solver_scalar_fields)
        name = solver_scalar_fields{index};
        if isfield(result.config,name) ...
                && (isempty(result.config.(name)) || isscalar(result.config.(name)))
            compact.(name) = result.config.(name);
        end
    end
end
end
