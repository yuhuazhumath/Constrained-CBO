function signature = experiment_checkpoint_signature(config)
%EXPERIMENT_CHECKPOINT_SIGNATURE Reconstructable generic-run identity.
problem = config.problem;
if isfield(problem,'metadata')
    problem_metadata = problem.metadata;
else
    problem_metadata = struct();
end
if isfield(config,'method_overrides')
    method_overrides = normalize_overrides(config.method_overrides);
else
    method_overrides = struct([]);
end
if isfield(config,'proposed_solver') && ~isempty(config.proposed_solver)
    proposed_solver = config.proposed_solver;
else
    proposed_solver = 'algorithm1';
end
signature = struct( ...
    'schema_version',1, ...
    'storage_mode','full-raw-v1', ...
    'case_id',config.id, ...
    'problem_name',problem.name, ...
    'problem_dimension',problem.dimension, ...
    'problem_metadata',problem_metadata, ...
    'vstar',problem.vstar, ...
    'objective_star',problem.objective_star, ...
    'methods',{config.methods}, ...
    'master_seed',config.master_seed, ...
    'repetitions',config.repetitions, ...
    'initial_seeds',arrayfun(@(r)derive_repetition_seed( ...
    config.master_seed,r,0),1:config.repetitions), ...
    'solver_seeds',arrayfun(@(r)derive_repetition_seed( ...
    config.master_seed,r,1),1:config.repetitions), ...
    'base_solver_config',revision_solver_config_metadata( ...
    config.solver_config), ...
    'method_overrides',method_overrides, ...
    'proposed_solver',proposed_solver);
end

function overrides = normalize_overrides(overrides)
for index=1:numel(overrides)
    overrides(index).solver_config = revision_solver_config_metadata( ...
        overrides(index).solver_config);
end
end
